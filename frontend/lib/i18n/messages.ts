export function detectLocaleFromNavigator(raw: string | undefined): Locale {
  const value = String(raw || '').toLowerCase()
  if (value.startsWith('de')) return 'de'
  if (value.startsWith('it')) return 'it'
  if (value.startsWith('en')) return 'en'
  return 'fr'
}

